// End-to-end check: every step can be done AND undone, and the guard rails refuse unsafe undos.
const B = "http://localhost:5173/api";
let cookie = "";
const call = async (p, body) => {
  const r = await fetch(B + p, { method: body === undefined ? "GET" : "POST", headers: { ...(body !== undefined ? { "Content-Type": "application/json" } : {}), ...(cookie ? { cookie } : {}) }, body: body === undefined ? undefined : JSON.stringify(body) });
  const sc = r.headers.get("set-cookie"); if (sc) cookie = sc.split(";")[0];
  return { s: r.status, j: await r.json().catch(() => ({})) };
};
const ok = async (p, b) => { const r = await call(p, b); if (r.s !== 200) throw new Error(`${p} → ${r.s} ${r.j.error}`); return r.j; };
let fails = 0;
const t = (name, pass, x = "") => { if (!pass) fails++; console.log(`${pass ? "PASS" : "FAIL"}  ${name}${x ? "  → " + x : ""}`); };
const refused = async (name, p, b) => { const r = await call(p, b); t(name, r.s === 400, r.j.error); };
const white = async () => (await ok("/meta")).loops.find((l) => l.color === "White").balance_kg;

await ok("/auth/login", { email: "owner@evergreen.test", password: "evergreen-demo" });

console.log("\n— Demo data integrity");
const sk = await ok("/sacks");
t("sacks in godown arrived by a challan", sk.groups.filter((g) => g.status === "godown").length === 0 || sk.challans.some((c) => c.kind === "Factory → Godown"));

console.log("\n— Fabric: order → edit → receive → undo → remove");
const meta = await ok("/meta");
await ok("/rolls/purchase", { vendor_id: 1, color: "Teal", size_in: 30, gsm: 60, quality: "Standard", count: 2, length_m: 1000, net_kg: 50 });
const inc = (await ok("/rolls?view=transit")).filter((r) => r.color === "Teal");
t("purchase creates 2 incoming rolls", inc.length === 2);
await ok(`/rolls/${inc[0].id}/edit`, { net_kg: 47.5 });
t("correct a roll's actual weight", (await ok("/rolls?view=transit")).find((r) => r.id === inc[0].id).net_kg === 47.5);
await ok("/rolls/receive", { ids: [inc[0].id] });
t("mark received", (await ok("/rolls?view=stock")).some((r) => r.id === inc[0].id));
await ok("/rolls/unreceive", { ids: [inc[0].id] });
t("UNDO: mark not received → back to incoming", (await ok("/rolls?view=transit")).some((r) => r.id === inc[0].id));
await ok("/rolls/cancel-incoming", { ids: inc.map((r) => r.id) });
t("remove incoming rolls entered by mistake", !(await ok("/rolls?view=transit")).some((r) => r.color === "Teal"));

console.log("\n— Order with handles: book → print → cut → pack → godown → client, undoing each");
const due = new Date(Date.now() + 5 * 864e5).toLocaleDateString("en-CA");
const loopsBefore = await white();
await ok("/rolls/purchase", { vendor_id: 1, color: "Navy", size_in: 32, gsm: 80, quality: "Premium", count: 1, length_m: 1000, net_kg: 130 });
const nr = (await ok("/rolls?view=transit")).find((r) => r.color === "Navy" && r.size_in === 32);
await ok("/rolls/receive", { ids: [nr.id] });
const o = await ok("/orders", { bag_type: "loop", client_id: 1, w: 13, l: 15, gsm: 80, qty: 2000, color: "Navy", quality: "Premium", loop_color: "White", due_date: due });
await ok(`/orders/${o.id}/book`, { roll_ids: [nr.id] });
await refused("refuse: unreceive a roll booked to an order", "/rolls/unreceive", { ids: [nr.id] });
await refused("refuse: change colour of a booked roll", `/rolls/${nr.id}/edit`, { color: "Red" });
await ok(`/rolls/${nr.id}/print`, { machine_id: 1 });
await refused("refuse: release a printed roll", `/orders/${o.id}/unbook/${nr.id}`, {});
await ok(`/rolls/${nr.id}/unprint`, {});
t("UNDO: printing", !(await ok(`/orders/${o.id}`)).rolls[0].printed_on);
await ok(`/rolls/${nr.id}/print`, { machine_id: 1 });
await refused("refuse: change bag size after printing", `/orders/${o.id}/edit`, { w: 14 });
await ok(`/orders/${o.id}/edit`, { notes: "Rush" });
t("notes/dates still editable after printing", (await ok(`/orders/${o.id}`)).notes === "Rush");
await ok(`/rolls/${nr.id}/cut`, { machine_id: 5, bags_out: 2500, waste_kg: 3 });
const afterCut = await white();
t("cutting loop bags takes handles from stock (2,500 × 3.4 g = 8.5 kg)", Math.abs(loopsBefore - afterCut - 8.5) < 0.01, `${loopsBefore} → ${afterCut} kg`);
await ok(`/orders/${o.id}/pack`, { sacks: 2, pieces: 1000, kg: 12 });
await refused("refuse: undo a cut whose bags are already packed", `/rolls/${nr.id}/uncut`, {});
let od = await ok(`/orders/${o.id}`);
await ok("/sacks/unpack", { ids: od.sacks.map((s) => s.id) });
t("UNDO: packing (unpack sacks)", (await ok(`/orders/${o.id}`)).sacks.length === 0);
await ok(`/rolls/${nr.id}/uncut`, {});
t("UNDO: cutting puts handles back", Math.abs((await white()) - loopsBefore) < 0.01, `${await white()} kg`);
await ok(`/rolls/${nr.id}/cut`, { machine_id: 5, bags_out: 2500, waste_kg: 3 });
await ok(`/orders/${o.id}/pack`, { sacks: 2, pieces: 1000, kg: 12 });
od = await ok(`/orders/${o.id}`);
const ids = od.sacks.map((s) => s.id);
const g = await ok("/sacks/move", { ids, to: "godown", vehicle: "WB-1" });
await refused("refuse: unpack sacks that are in the godown", "/sacks/unpack", { ids });
await ok("/sacks/move", { ids, to: "factory", vehicle: "WB-2" });
t("move godown → factory", (await ok(`/orders/${o.id}`)).sacks.every((s) => s.status === "factory"));
await ok("/sacks/move", { ids, to: "godown", vehicle: "WB-3" });
const d = await ok("/sacks/move", { ids, to: "dispatched", vehicle: "WB-4" });
t("order closes itself when every bag is sent", (await ok(`/orders/${o.id}`)).status === "delivered");
const challans = (await ok("/sacks")).challans;
await ok(`/challans/${challans.find((c) => c.challan_no === d.challan_no).id}/cancel`, { reason: "wrong truck" });
od = await ok(`/orders/${o.id}`);
t("UNDO: cancel delivery challan → sacks back in godown, order reopened", od.sacks.every((s) => s.status === "godown") && od.status === "open");
t("an older challan can't be cancelled while a later one still holds the sacks", !(await ok("/sacks")).challans.find((c) => c.challan_no === g.challan_no).canCancel);

console.log("\n— Orders: close / cancel / reopen");
await ok(`/orders/${o.id}/close`, { note: "Client accepted short delivery" });
t("close as delivered (short shipment)", (await ok(`/orders/${o.id}`)).status === "delivered");
await ok(`/orders/${o.id}/reopen`, {});
t("UNDO: reopen", (await ok(`/orders/${o.id}`)).status === "open");
const o2 = await ok("/orders", { bag_type: "dcut", client_id: 2, w: 10, l: 14, gsm: 60, qty: 1000, color: "White", quality: "Premium", due_date: due });
await ok(`/orders/${o2.id}/book`, {});
await ok(`/orders/${o2.id}/cancel`, {});
t("cancel order releases its rolls", (await ok(`/orders/${o2.id}`)).rolls.length === 0);
await ok(`/orders/${o2.id}/reopen`, {});
t("UNDO: reopen cancelled order", (await ok(`/orders/${o2.id}`)).status === "open");

console.log("\n— Reference data");
const v = await ok("/vendors", { name: "Test Mills", city: "Surat" });
await ok(`/vendors/${v.id}`, { active: false });
await refused("refuse: buy from an inactive supplier", "/rolls/purchase", { vendor_id: v.id, color: "X", size_in: 1, gsm: 20, count: 1, length_m: 1, net_kg: 1 });
await ok(`/vendors/${v.id}`, { active: true });
t("UNDO: reactivate supplier", (await ok("/meta")).vendors.find((x) => x.id === v.id).active === 1);
const m = await ok("/machines", { name: "Cutter E", kind: "cutting" });
await ok(`/machines/${m.id}`, { active: false });
t("retired machine disappears from production", !(await ok("/production")).machines.some((x) => x.id === m.id));
await ok("/clients/1", { phone: "9800000000" });
t("edit a client", (await ok("/meta")).clients.find((c) => c.id === 1).phone === "9800000000");
const lim = (await ok("/meta")).limits[0];
await ok(`/limits/${lim.id}/delete`, {}); await ok("/limits", lim);
t("remove and re-add a fabric minimum", (await ok("/meta")).limits.length === meta.limits.length);
const before = await white();
await ok(`/loops/${(await ok("/meta")).loops.find((l) => l.color === "White").id}/receive`, { kg: 50 });
t("record a handle delivery", (await white()) === before + 50);

console.log("\nLatest activity log:");
(await ok("/activity")).slice(0, 4).forEach((a) => console.log(`  ${a.text} — ${a.user}`));
console.log(`\n${fails ? fails + " FAILED" : "All passed"}`);
